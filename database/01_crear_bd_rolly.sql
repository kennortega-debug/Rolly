-- 1. PRODUCTOS
CREATE TABLE producto (
    id_producto       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre            VARCHAR2(100) NOT NULL,
    marca             VARCHAR2(60) NOT NULL,
    modelo            VARCHAR2(80) NOT NULL,
    talla              NUMBER(2) NOT NULL,
    color              VARCHAR2(40) NOT NULL,
    categoria          VARCHAR2(40) DEFAULT 'Urbana' NOT NULL,
    precio             NUMBER(10,0) NOT NULL,
    stock              NUMBER(3) NOT NULL,
    fecha_creacion     DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_producto PRIMARY KEY (id_producto),
    CONSTRAINT ck_producto_precio CHECK (precio BETWEEN 15000 AND 32000),
    CONSTRAINT ck_producto_stock CHECK (stock BETWEEN 10 AND 100),
    CONSTRAINT ck_producto_talla CHECK (talla BETWEEN 20 AND 50)
);

-- 2. VENTAS
CREATE TABLE venta (
    id_venta           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    fecha_venta        DATE DEFAULT SYSDATE NOT NULL,
    estado             VARCHAR2(15) DEFAULT 'ABIERTA' NOT NULL,
    total              NUMBER(12,0) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_venta PRIMARY KEY (id_venta),
    CONSTRAINT ck_venta_estado CHECK (estado IN ('ABIERTA', 'CERRADA', 'ANULADA')),
    CONSTRAINT ck_venta_total CHECK (total >= 0)
);

-- 3. DETALLE DE VENTAS
CREATE TABLE detalle_venta (
    id_detalle         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_venta           NUMBER NOT NULL,
    id_producto        NUMBER NOT NULL,
    cantidad           NUMBER(3) NOT NULL,
    precio_unitario    NUMBER(10,0) NOT NULL,
    subtotal           NUMBER(12,0) NOT NULL,
    CONSTRAINT pk_detalle_venta PRIMARY KEY (id_detalle),
    CONSTRAINT fk_detalle_venta FOREIGN KEY (id_venta) REFERENCES venta(id_venta),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto) REFERENCES producto(id_producto),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario BETWEEN 15000 AND 32000),
    CONSTRAINT ck_detalle_subtotal CHECK (subtotal = cantidad * precio_unitario)
);

-- 4. MOVIMIENTOS DE INVENTARIO
CREATE TABLE movimientos_inventario (
    id_movimiento      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_producto        NUMBER NOT NULL,
    tipo_movimiento    VARCHAR2(10) NOT NULL,
    cantidad           NUMBER(3) NOT NULL,
    stock_anterior     NUMBER(3) NOT NULL,
    stock_nuevo        NUMBER(3) NOT NULL,
    fecha_movimiento   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    observacion        VARCHAR2(250),
    CONSTRAINT pk_movimientos_inventario PRIMARY KEY (id_movimiento),
    CONSTRAINT fk_mov_producto FOREIGN KEY (id_producto) REFERENCES producto(id_producto),
    CONSTRAINT ck_mov_tipo CHECK (tipo_movimiento IN ('ENTRADA', 'SALIDA', 'AJUSTE')),
    CONSTRAINT ck_mov_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_mov_stock_anterior CHECK (stock_anterior BETWEEN 10 AND 100),
    CONSTRAINT ck_mov_stock_nuevo CHECK (stock_nuevo BETWEEN 10 AND 100)
);

-- 5. AUDITORÍA DE EVENTOS
CREATE TABLE auditoria_eventos (
    id_evento          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    tabla_afectada     VARCHAR2(50) NOT NULL,
    operacion          VARCHAR2(20) NOT NULL,
    descripcion       VARCHAR2(400),
    fecha_evento       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    usuario_bd         VARCHAR2(128) DEFAULT USER NOT NULL,
    CONSTRAINT pk_auditoria_eventos PRIMARY KEY (id_evento)
);

-- Índices para relaciones y consultas habituales
CREATE INDEX ix_detalle_venta_venta ON detalle_venta(id_venta);
CREATE INDEX ix_detalle_venta_producto ON detalle_venta(id_producto);
CREATE INDEX ix_movimientos_producto ON movimientos_inventario(id_producto);
CREATE INDEX ix_venta_fecha ON venta(fecha_venta);

